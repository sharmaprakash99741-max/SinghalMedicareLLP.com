window.setLang = function(lang){
  document.documentElement.setAttribute("data-lang", lang);
  document.documentElement.setAttribute("lang", lang);
  localStorage.setItem("sm-lang", lang);
  const dict = window.I18N[lang] || window.I18N.en;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.getAttribute("data-i18n");
    if(dict[key] != null){
      if(key === "dr.lead" || key === "ph.lead" || key === "ab.p1" || key === "ab.p2" || key === "ab.p3"){
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });
  const t = document.getElementById("langToggle");
  if(t) t.setAttribute("data-active", lang);
  const inp = document.getElementById("medName");
  if(inp) inp.placeholder = dict["ph.placeholder"];
  const s = document.getElementById("docSearch");
  if(s) s.placeholder = dict["dr.search"];
  if(typeof window.refreshDynamic === "function") window.refreshDynamic();
};

window.t = function(key, fallback){
  const lang = document.documentElement.getAttribute("data-lang") || "en";
  const dict = window.I18N[lang] || window.I18N.en;
  return dict[key] != null ? dict[key] : (fallback != null ? fallback : key);
};
